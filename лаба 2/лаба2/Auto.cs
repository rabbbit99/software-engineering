using System;
using System.Collections.Generic;
using System.Text;
//Реализовать класс Auto для описания автомобиля для расчета транспортного налога (автомобиль описывается – маркой, мощностью двигателя (л.с.)). 
//Класс Auto должен иметь следующие методы:
//- задание данных об автомобиле;
//- вывод всех данных об автомобиле в виде строкового описания;
//-	расчет суммы транспортного налога для автомобиля;
//Реализовать класс для описания группы автомобилей Garage. Класс Garage должен иметь следующие методы:
//-	сортировка списка автомобилей в порядке возрастания их мощности двигателя.
//Формула расчета транспортного налога: 
//Транспортный налог = мощность двигателя * ставка налога,
//где, ставка налога:	
//    при мощности двигателя менее 100 л.с. – 9 руб. за 1 л.с.;
//    при объеме двигателя от 100 до 150 л.с. – 20 руб за 1 л.с.;
//    при объеме двигателя от 150 до 200 л.с. – 40 руб за 1 л.с.;
//    при объеме двигателя от 200 до 250 л.с. – 75 руб за 1 л.с.;
//    при объеме двигателя свыше 250 л.с. – 150 руб за 1 л.с.

namespace Lb3_autoPower
{
    class Auto
    {
        string марка;
        string мощность;
        string налог;

        public Auto()//конструктор без параметров
        {
            марка = ""; мощность = ""; налог = "";
        }

        public Auto(string марка, string мощность, string налог)
        {
            this.марка = марка;
            this.мощность = мощность;
            this.налог = налог;
        }

        public string Описание()
        {
            return string.Format("{0},{1},{2}", марка, мощность, налог);
        }

        public int ПолучитьМощность()
        {
            return int.Parse(мощность);
        }
    }
}
